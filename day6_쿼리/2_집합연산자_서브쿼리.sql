-- GROUP BY

SELECT STU_DEPT, STU_GRADE, AVG(STU_HEIGHT)
FROM STUDENT
GROUP BY STU_DEPT, STU_GRADE;

-- ROLLUP
SELECT STU_DEPT, STU_GRADE, AVG(STU_HEIGHT)
FROM STUDENT
GROUP BY ROLLUP(STU_DEPT, STU_GRADE);


SELECT STU_DEPT, STU_GRADE, AVG(STU_HEIGHT)
FROM STUDENT
GROUP BY STU_DEPT, STU_GRADE
UNION
SELECT STU_DEPT, NULL, AVG(STU_HEIGHT)
FROM STUDENT
GROUP BY STU_DEPT
UNION
SELECT NULL, NULL, AVG(STU_HEIGHT)
FROM STUDENT;


-- CUBE
SELECT STU_DEPT, STU_GRADE, AVG(STU_HEIGHT)
FROM STUDENT
GROUP BY CUBE(STU_DEPT, STU_GRADE)
ORDER BY STU_DEPT, STU_GRADE;


