-- RANK
SELECT * FROM ENROL;

SELECT stu_no, sub_no, enr_grade,
  RANK() OVER(ORDER BY enr_grade DESC) AS rnk,
  DENSE_RANK() OVER(ORDER BY enr_grade DESC) AS dense_rnk,
  ROW_NUMBER() OVER(ORDER BY enr_grade DESC) AS row_num
FROM enrol;

-- PARTITION

SELECT stu_dept, stu_name, stu_height,
  RANK() OVER(
    PARTITION BY stu_dept   -- 학과 단위로 파티션(벽)을 친다
    ORDER BY stu_height DESC
  ) AS dept_height_rnk
FROM student
WHERE stu_height IS NOT NULL;






